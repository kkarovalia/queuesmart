function UserDisplay({ userQuery }: {userQuery: UserQuery}) {
  if (userQuery.isLoading) {
    return (
      <h3>Loading...</h3>
    )
  }
  if (userQuery.error) {
    return (
      <h3>Error!</h3>
    ) // Would ideally route back to login or somewhere else
  }
  if (!userQuery.data) {
    return (
      <h3>Could not load user.</h3>
    )
  }
  return (
    <h3>
      Welcome {userQuery.data.name}!
    </h3>
  )
}

